-- ATLAS Billing Audit Plane
create table if not exists public.atlas_billing_events (
    id bigint generated by default as identity primary key,
    stripe_event_id text not null unique,
    event_type text not null,
    plan text,
    customer_id text,
    subscription_id text,
    customer_email text,
    subscription_status text,
    payload jsonb not null default '{}'::jsonb,
    created_at timestamptz not null default timezone('utc', now())
);

create index if not exists atlas_billing_events_customer_id_idx
    on public.atlas_billing_events (customer_id);
create index if not exists atlas_billing_events_subscription_id_idx
    on public.atlas_billing_events (subscription_id);

alter table public.atlas_billing_events enable row level security;
revoke all on table public.atlas_billing_events from anon, authenticated;
grant select, insert, update, delete on table public.atlas_billing_events to service_role;
grant usage, select on sequence public.atlas_billing_events_id_seq to service_role;
